-- Öğrenci yoklaması: öğrenci başına gün başına en fazla bir kayıt (geldi / gelmedi / izinli).
-- Kaydı olmayan öğrenci "işaretlenmemiş" demektir. Öğrenci silinirse yoklama kayıtları da silinir.
CREATE TABLE yoklama (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isletme_id        BIGINT       NOT NULL REFERENCES isletme (id),
    ogrenci_id        BIGINT       NOT NULL REFERENCES ogrenci (id) ON DELETE CASCADE,
    tarih             DATE         NOT NULL,
    durum             VARCHAR(20)  NOT NULL CHECK (durum IN ('GELDI', 'GELMEDI', 'IZINLI')),
    aciklama          VARCHAR(255),
    kullanici_id      BIGINT       REFERENCES kullanici (id),
    olusturma_tarihi  TIMESTAMP(6) NOT NULL,
    guncelleme_tarihi TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_yoklama_ogrenci_tarih UNIQUE (ogrenci_id, tarih)
);

CREATE INDEX idx_yoklama_isletme_tarih ON yoklama (isletme_id, tarih);

