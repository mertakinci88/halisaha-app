-- Envanter (forma, eşofman vb.) ve öğrencilere set olarak satışı.
-- Stok yalnızca teslim edilen kalem için düşer (teslim_edildi = true); teslim geri alınırsa / satış silinirse geri döner.
-- Satış kaleminde birim fiyat satış anındaki fiyatın kopyasıdır; envanter fiyatı sonradan değişse de geçmiş satış değişmez.

CREATE TABLE envanter (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isletme_id       BIGINT         NOT NULL REFERENCES isletme (id),
    tur              VARCHAR(30)    NOT NULL CHECK (tur IN ('KISLIK_ESOFMAN', 'KRAMPON_CANTASI', 'TOZLUK', 'YAGMURLUK', 'YAZLIK_FORMA')),
    beden            VARCHAR(10)    NOT NULL CHECK (beden IN ('STANDART', '128', '140', '152', '164', '176', 'Small', 'Medium')),
    adet             INTEGER        NOT NULL CHECK (adet >= 0),
    stok_uyari_adedi INTEGER        NOT NULL DEFAULT 10 CHECK (stok_uyari_adedi >= 0),
    satis_fiyati     NUMERIC(10, 2) NOT NULL CHECK (satis_fiyati > 0),
    CONSTRAINT uk_envanter_tur_beden UNIQUE (isletme_id, tur, beden),
    -- Bedenli türlerde gerçek beden, diğerlerinde STANDART tutulur
    CONSTRAINT envanter_beden_tutarli CHECK (
        (tur IN ('KISLIK_ESOFMAN', 'YAGMURLUK', 'YAZLIK_FORMA')) = (beden <> 'STANDART'))
);

CREATE TABLE envanter_satis (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isletme_id        BIGINT         NOT NULL REFERENCES isletme (id),
    ogrenci_id        BIGINT         NOT NULL REFERENCES ogrenci (id),
    set_tutari        NUMERIC(10, 2) NOT NULL CHECK (set_tutari > 0),
    odenen_tutar      NUMERIC(10, 2) NOT NULL CHECK (odenen_tutar >= 0),
    kullanici_id      BIGINT         REFERENCES kullanici (id),
    kayit_tarihi      TIMESTAMP(6)   NOT NULL,
    guncelleme_tarihi TIMESTAMP(6)   NOT NULL,
    CHECK (odenen_tutar <= set_tutari)
);

CREATE INDEX idx_envanter_satis_ogrenci ON envanter_satis (isletme_id, ogrenci_id);

CREATE TABLE envanter_satis_kalem (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    satis_id      BIGINT         NOT NULL REFERENCES envanter_satis (id) ON DELETE CASCADE,
    envanter_id   BIGINT         NOT NULL REFERENCES envanter (id),
    birim_fiyat   NUMERIC(10, 2) NOT NULL CHECK (birim_fiyat >= 0),
    odendi        BOOLEAN        NOT NULL DEFAULT FALSE,
    teslim_edildi BOOLEAN        NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_envanter_satis_kalem_satis ON envanter_satis_kalem (satis_id);
CREATE INDEX idx_envanter_satis_kalem_envanter ON envanter_satis_kalem (envanter_id);

CREATE TABLE envanter_stok_hareket (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    envanter_id   BIGINT       NOT NULL REFERENCES envanter (id) ON DELETE CASCADE,
    -- Satış silinse de hareket geçmişi kalır
    satis_id      BIGINT       REFERENCES envanter_satis (id) ON DELETE SET NULL,
    tip           VARCHAR(10)  NOT NULL CHECK (tip IN ('TESLIM', 'IADE', 'DUZELTME')),
    degisim       INTEGER      NOT NULL CHECK (degisim <> 0),
    kalan_adet    INTEGER      NOT NULL CHECK (kalan_adet >= 0),
    aciklama      VARCHAR(255),
    kullanici_id  BIGINT       REFERENCES kullanici (id),
    olusma_tarihi TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_envanter_stok_hareket ON envanter_stok_hareket (envanter_id, olusma_tarihi);

