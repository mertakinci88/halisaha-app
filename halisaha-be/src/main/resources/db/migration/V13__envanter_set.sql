-- Envanter setleri: işletmenin önceden tanımladığı, envanter kayıtlarından (tür + beden) oluşan paketler.
-- Satışta set seçilince kalemler hazır gelir; satış kaydı set adının kopyasını da tutar (set silinse / adı değişse bile görünür).

CREATE TABLE envanter_set (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isletme_id        BIGINT       NOT NULL REFERENCES isletme (id),
    ad                VARCHAR(100) NOT NULL,
    kullanici_id      BIGINT       REFERENCES kullanici (id),
    kayit_tarihi      TIMESTAMP(6) NOT NULL,
    guncelleme_tarihi TIMESTAMP(6) NOT NULL
);

-- Set adı işletme içinde büyük/küçük harf farkı gözetmeden tekil
CREATE UNIQUE INDEX uk_envanter_set_ad ON envanter_set (isletme_id, LOWER(ad));

CREATE TABLE envanter_set_kalem (
    set_id      BIGINT NOT NULL REFERENCES envanter_set (id) ON DELETE CASCADE,
    envanter_id BIGINT NOT NULL REFERENCES envanter (id),
    PRIMARY KEY (set_id, envanter_id)
);

CREATE INDEX idx_envanter_set_kalem_envanter ON envanter_set_kalem (envanter_id);

ALTER TABLE envanter_satis ADD COLUMN set_id BIGINT REFERENCES envanter_set (id) ON DELETE SET NULL;
ALTER TABLE envanter_satis ADD COLUMN set_ad VARCHAR(100);
