-- Havale / EFT hesapları (işletme bazında). Kapora/ödeme alınırken ve öğrenci ödeme bilgisinde
-- Havale / EFT seçilirse paranın hangi hesaba yattığı bu tablodan seçilir.
-- Kullanılmış bir hesap silinmez, pasife alınır (geçmiş kayıtlar hesap adını göstermeye devam eder).

CREATE TABLE hesap (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isletme_id   BIGINT       NOT NULL REFERENCES isletme (id),
    ad           VARCHAR(255) NOT NULL,
    iban         VARCHAR(26)  NOT NULL,
    hesap_sahibi VARCHAR(255) NOT NULL,
    durum        VARCHAR(20)  NOT NULL CHECK (durum IN ('AKTIF', 'PASIF')),
    kayit_tarih  TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_hesap_isletme ON hesap (isletme_id);

ALTER TABLE odeme   ADD COLUMN hesap_id BIGINT REFERENCES hesap (id);
ALTER TABLE ogrenci ADD COLUMN hesap_id BIGINT REFERENCES hesap (id);

