-- Öğrenci aidatı artık ay ay tutulur: her ay için bir ogrenci_odeme kaydı (yıl + ay).
-- aidat_tutari, kayıt anındaki aylık aidatın kopyasıdır; aidat sonradan değişse de geçmiş aylar etkilenmez.
-- Kayıt yalnızca ödeme alınmış aylar için vardır (odenen_tutar > 0); kaydı olmayan ay "Ödenmedi" sayılır.
-- Ödeme durumu (Ödendi / Kısmi ödendi / Ödenmedi) odenen_tutar ile aidat_tutari'ndan türetilir, saklanmaz.

CREATE TABLE ogrenci_odeme (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ogrenci_id   BIGINT         NOT NULL REFERENCES ogrenci (id) ON DELETE CASCADE,
    yil          INTEGER        NOT NULL CHECK (yil BETWEEN 2000 AND 2100),
    ay           INTEGER        NOT NULL CHECK (ay BETWEEN 1 AND 12),
    aidat_tutari NUMERIC(10, 2) NOT NULL CHECK (aidat_tutari > 0),
    odenen_tutar NUMERIC(10, 2) NOT NULL CHECK (odenen_tutar > 0),
    odeme_sekli  VARCHAR(20)    NOT NULL CHECK (odeme_sekli IN ('NAKIT', 'KART', 'HAVALE_EFT')),
    hesap_id     BIGINT         REFERENCES hesap (id),
    odeme_tarihi DATE           NOT NULL,
    kullanici_id BIGINT         REFERENCES kullanici (id),
    kayit_tarih  TIMESTAMP(6)   NOT NULL,
    CONSTRAINT ogrenci_odeme_tutar_sinir CHECK (odenen_tutar <= aidat_tutari),
    CONSTRAINT ogrenci_odeme_hesap_tutarli CHECK ((odeme_sekli = 'HAVALE_EFT') = (hesap_id IS NOT NULL)),
    CONSTRAINT ogrenci_odeme_ay_tekil UNIQUE (ogrenci_id, yil, ay)
);

CREATE INDEX idx_ogrenci_odeme_donem ON ogrenci_odeme (yil, ay);

-- Eski tek satırlık ödeme bilgisi: ödeme tarihi ve tutarı olan öğrencinin son ödemesi, o tarihin ayına taşınır.
INSERT INTO ogrenci_odeme (ogrenci_id, yil, ay, aidat_tutari, odenen_tutar, odeme_sekli, hesap_id, odeme_tarihi, kayit_tarih)
SELECT g.id,
       EXTRACT(YEAR FROM g.odeme_tarihi)::int,
       EXTRACT(MONTH FROM g.odeme_tarihi)::int,
       GREATEST(g.aylik_aidat, g.odenen_tutar),
       LEAST(g.odenen_tutar, GREATEST(g.aylik_aidat, g.odenen_tutar)),
       COALESCE(g.odeme_sekli, 'NAKIT'),
       CASE WHEN g.odeme_sekli = 'HAVALE_EFT' THEN g.hesap_id END,
       g.odeme_tarihi,
       now()
FROM ogrenci g
WHERE g.odeme_tarihi IS NOT NULL
  AND g.odenen_tutar > 0
  AND (g.odeme_sekli IS DISTINCT FROM 'HAVALE_EFT' OR g.hesap_id IS NOT NULL)
  AND EXTRACT(YEAR FROM g.odeme_tarihi) BETWEEN 2000 AND 2100;

ALTER TABLE ogrenci
    DROP COLUMN odeme_durumu,
    DROP COLUMN odeme_plani,
    DROP COLUMN odenen_donem,
    DROP COLUMN odeme_tarihi,
    DROP COLUMN sonraki_odeme_tarih,
    DROP COLUMN odenen_tutar,
    DROP COLUMN odeme_sekli,
    DROP COLUMN hesap_id;
