-- Halısaha veritabanı şeması: tüm tablolar, kısıtlar ve indeksler ilk kez oluşturuluyormuş gibi tek dosyada.
-- Her tabloda kolon sırası: id, diğer *_id (yabancı anahtar) kolonları, sonra diğer kolonlar.
-- Envanter türleri: KISLIK_ESOFMAN, KRAMPON_CANTASI, TOZLUK, YAGMURLUK, YAZLIK_FORMA, KALECI_FORMA (bedenli olanlarda gerçek beden, diğerlerinde STANDART).
-- Dosyanın sonunda yalnızca işletmeler yer alır; kullanıcı, rezervasyon vb. canlı verisi repoda tutulmaz, canlıya ayrı betikle aktarılır.

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE isletme (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ad character varying(255) NOT NULL,
    yonetici_ad_soyad character varying(255),
    yonetici_tel_no character varying(255),
    durum character varying(20) NOT NULL,
    kayit_tarih timestamp(6) without time zone NOT NULL,
    CONSTRAINT isletme_pkey PRIMARY KEY (id),
    CONSTRAINT isletme_durum_check CHECK (durum IN ('AKTIF', 'PASIF'))
);


CREATE TABLE abonelik_ayar (
    isletme_id bigint NOT NULL,
    standart_ucret numeric(10,2) NOT NULL,
    CONSTRAINT abonelik_ayar_pkey PRIMARY KEY (isletme_id),
    CONSTRAINT abonelik_ayar_standart_ucret_check CHECK (standart_ucret >= 0),
    CONSTRAINT abonelik_ayar_isletme_id_fkey FOREIGN KEY (isletme_id) REFERENCES isletme(id)
);


CREATE TABLE envanter (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    isletme_id bigint NOT NULL,
    tur character varying(30) NOT NULL,
    beden character varying(10) NOT NULL,
    adet integer NOT NULL,
    stok_uyari_adedi integer DEFAULT 10 NOT NULL,
    satis_fiyati numeric(10,2) NOT NULL,
    CONSTRAINT envanter_pkey PRIMARY KEY (id),
    CONSTRAINT uk_envanter_tur_beden UNIQUE (isletme_id, tur, beden),
    CONSTRAINT envanter_adet_check CHECK (adet >= 0),
    CONSTRAINT envanter_beden_check CHECK (beden IN ('STANDART', '128', '140', '152', '164', '176', 'Small', 'Medium')),
    CONSTRAINT envanter_beden_tutarli CHECK ((tur IN ('KISLIK_ESOFMAN', 'YAGMURLUK', 'YAZLIK_FORMA', 'KALECI_FORMA')) = ((beden) <> 'STANDART')),
    CONSTRAINT envanter_satis_fiyati_check CHECK (satis_fiyati > 0),
    CONSTRAINT envanter_stok_uyari_adedi_check CHECK (stok_uyari_adedi >= 0),
    CONSTRAINT envanter_tur_check CHECK (tur IN ('KISLIK_ESOFMAN', 'KRAMPON_CANTASI', 'TOZLUK', 'YAGMURLUK', 'YAZLIK_FORMA', 'KALECI_FORMA')),
    CONSTRAINT envanter_isletme_id_fkey FOREIGN KEY (isletme_id) REFERENCES isletme(id)
);


CREATE TABLE grup (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    isletme_id bigint NOT NULL,
    ad character varying(255) NOT NULL,
    CONSTRAINT grup_pkey PRIMARY KEY (id),
    CONSTRAINT grup_isletme_id_fkey FOREIGN KEY (isletme_id) REFERENCES isletme(id)
);

CREATE INDEX idx_grup_isletme ON grup USING btree (isletme_id);

CREATE TABLE hesap (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    isletme_id bigint NOT NULL,
    ad character varying(255) NOT NULL,
    iban character varying(26) NOT NULL,
    hesap_sahibi character varying(255) NOT NULL,
    durum character varying(20) NOT NULL,
    kayit_tarih timestamp(6) without time zone NOT NULL,
    CONSTRAINT hesap_pkey PRIMARY KEY (id),
    CONSTRAINT hesap_durum_check CHECK (durum IN ('AKTIF', 'PASIF')),
    CONSTRAINT hesap_isletme_id_fkey FOREIGN KEY (isletme_id) REFERENCES isletme(id)
);

CREATE INDEX idx_hesap_isletme ON hesap USING btree (isletme_id);

CREATE TABLE kullanici (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    isletme_id bigint,
    kullanici_adi character varying(255) NOT NULL,
    sifre character varying(255) NOT NULL,
    ad_soyad character varying(255) NOT NULL,
    rol character varying(20) NOT NULL,
    durum character varying(20) NOT NULL,
    kayit_tarih timestamp(6) without time zone NOT NULL,
    grup_kisitli boolean DEFAULT false NOT NULL,
    CONSTRAINT kullanici_pkey PRIMARY KEY (id),
    CONSTRAINT kullanici_kullanici_adi_key UNIQUE (kullanici_adi),
    CONSTRAINT kullanici_durum_check CHECK (durum IN ('AKTIF', 'PASIF')),
    CONSTRAINT kullanici_isletme_check CHECK (((rol) = 'SUPER_ADMIN') = (isletme_id IS NULL)),
    CONSTRAINT kullanici_rol_check CHECK (rol IN ('SUPER_ADMIN', 'ADMIN', 'PERSONEL')),
    CONSTRAINT kullanici_isletme_id_fkey FOREIGN KEY (isletme_id) REFERENCES isletme(id)
);

CREATE INDEX idx_kullanici_isletme ON kullanici USING btree (isletme_id);

CREATE TABLE saha (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    isletme_id bigint NOT NULL,
    ad character varying(255) NOT NULL,
    durum character varying(20) NOT NULL,
    saatlik_ucret numeric(10,2) NOT NULL,
    CONSTRAINT saha_pkey PRIMARY KEY (id),
    CONSTRAINT saha_durum_check CHECK (durum IN ('AKTIF', 'PASIF')),
    CONSTRAINT saha_isletme_id_fkey FOREIGN KEY (isletme_id) REFERENCES isletme(id)
);

CREATE INDEX idx_saha_isletme ON saha USING btree (isletme_id);

CREATE TABLE urun (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    isletme_id bigint NOT NULL,
    ad character varying(255) NOT NULL,
    adet integer NOT NULL,
    fiyat numeric(10,2) NOT NULL,
    stok_uyari_adedi integer DEFAULT 10 NOT NULL,
    CONSTRAINT urun_pkey PRIMARY KEY (id),
    CONSTRAINT urun_adet_check CHECK (adet >= 0),
    CONSTRAINT urun_stok_uyari_adedi_check CHECK (stok_uyari_adedi >= 0),
    CONSTRAINT urun_isletme_id_fkey FOREIGN KEY (isletme_id) REFERENCES isletme(id)
);

CREATE INDEX idx_urun_isletme ON urun USING btree (isletme_id);

CREATE TABLE abonelik (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    isletme_id bigint NOT NULL,
    saha_id bigint NOT NULL,
    kullanici_id bigint,
    iptal_eden_id bigint,
    ad_soyad character varying(255) NOT NULL,
    tel_no character varying(11) NOT NULL,
    hafta_gunu integer NOT NULL,
    baslangic_tarih date NOT NULL,
    bitis_tarih date NOT NULL,
    durum character varying(20) NOT NULL,
    depozito numeric(10,2) NOT NULL,
    iptal_tarih timestamp(6) without time zone,
    "not" character varying(255),
    kayit_tarih timestamp(6) without time zone NOT NULL,
    baslangic_dakika integer NOT NULL,
    sure_dakika integer NOT NULL,
    iptal_neden character varying(255),
    haftalik_ucret numeric(10,2) NOT NULL,
    CONSTRAINT abonelik_pkey PRIMARY KEY (id),
    CONSTRAINT uk_abonelik_id_isletme UNIQUE (id, isletme_id),
    CONSTRAINT abonelik_baslangic_dakika_aralik CHECK ((baslangic_dakika >= 720) AND (baslangic_dakika <= 1530) AND ((baslangic_dakika % 30) = 0)),
    CONSTRAINT abonelik_durum_check CHECK (durum IN ('AKTIF', 'IPTAL')),
    CONSTRAINT abonelik_hafta_gunu_check CHECK ((hafta_gunu >= 1) AND (hafta_gunu <= 7)),
    CONSTRAINT abonelik_haftalik_ucret_check CHECK (haftalik_ucret > 0),
    CONSTRAINT abonelik_saat_sinir CHECK ((baslangic_dakika + sure_dakika) <= 1560),
    CONSTRAINT abonelik_sure_dakika_aralik CHECK ((sure_dakika >= 30) AND ((sure_dakika % 30) = 0)),
    CONSTRAINT abonelik_tarih_sira CHECK (bitis_tarih > baslangic_tarih),
    CONSTRAINT abonelik_ucret_check CHECK (depozito > 0),
    CONSTRAINT abonelik_iptal_eden_id_fkey FOREIGN KEY (iptal_eden_id) REFERENCES kullanici(id),
    CONSTRAINT abonelik_isletme_id_fkey FOREIGN KEY (isletme_id) REFERENCES isletme(id),
    CONSTRAINT abonelik_kullanici_id_fkey FOREIGN KEY (kullanici_id) REFERENCES kullanici(id),
    CONSTRAINT abonelik_saha_id_fkey FOREIGN KEY (saha_id) REFERENCES saha(id)
);

CREATE INDEX idx_abonelik_isletme ON abonelik USING btree (isletme_id, durum);
CREATE INDEX idx_abonelik_saha ON abonelik USING btree (saha_id);

CREATE TABLE envanter_set (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    isletme_id bigint NOT NULL,
    kullanici_id bigint,
    ad character varying(100) NOT NULL,
    kayit_tarihi timestamp(6) without time zone NOT NULL,
    guncelleme_tarihi timestamp(6) without time zone NOT NULL,
    CONSTRAINT envanter_set_pkey PRIMARY KEY (id),
    CONSTRAINT envanter_set_isletme_id_fkey FOREIGN KEY (isletme_id) REFERENCES isletme(id),
    CONSTRAINT envanter_set_kullanici_id_fkey FOREIGN KEY (kullanici_id) REFERENCES kullanici(id)
);

CREATE UNIQUE INDEX uk_envanter_set_ad ON envanter_set USING btree (isletme_id, lower((ad)));

CREATE TABLE kullanici_grup (
    kullanici_id bigint NOT NULL,
    grup_id bigint NOT NULL,
    CONSTRAINT kullanici_grup_pkey PRIMARY KEY (kullanici_id, grup_id),
    CONSTRAINT kullanici_grup_grup_id_fkey FOREIGN KEY (grup_id) REFERENCES grup(id) ON DELETE CASCADE,
    CONSTRAINT kullanici_grup_kullanici_id_fkey FOREIGN KEY (kullanici_id) REFERENCES kullanici(id) ON DELETE CASCADE
);


CREATE TABLE kullanici_yetki (
    kullanici_id bigint NOT NULL,
    modul character varying(30) NOT NULL,
    CONSTRAINT kullanici_yetki_pkey PRIMARY KEY (kullanici_id, modul),
    CONSTRAINT kullanici_yetki_modul_check CHECK (modul IN ('OGRENCI', 'GRUP', 'SAHA', 'URUN', 'YOKLAMA', 'ENVANTER', 'HESAP', 'TRANSFER', 'ABONELIK', 'OGRENCI_TRANSFER', 'OGRENCI_ODEME', 'OGRENCI_ENVANTER')),
    CONSTRAINT kullanici_yetki_kullanici_id_fkey FOREIGN KEY (kullanici_id) REFERENCES kullanici(id)
);


CREATE TABLE ogrenci (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    grup_id bigint,
    isletme_id bigint NOT NULL,
    ad_soyad character varying(255) NOT NULL,
    dogum_tarih date,
    veli_ad_soyad character varying(255),
    veli_tel_no character varying(255),
    durum character varying(20) NOT NULL,
    antrenman_gun_sayisi integer,
    kayit_tarih timestamp(6) without time zone NOT NULL,
    "not" character varying(255),
    CONSTRAINT ogrenci_pkey PRIMARY KEY (id),
    CONSTRAINT uk_ogrenci_id_isletme UNIQUE (id, isletme_id),
    CONSTRAINT ogrenci_durum_check CHECK (durum IN ('AKTIF', 'PASIF')),
    CONSTRAINT ogrenci_grup_id_fkey FOREIGN KEY (grup_id) REFERENCES grup(id),
    CONSTRAINT ogrenci_isletme_id_fkey FOREIGN KEY (isletme_id) REFERENCES isletme(id)
);

CREATE INDEX idx_ogrenci_ad_trgm ON ogrenci USING gin (lower((ad_soyad)) gin_trgm_ops);
CREATE INDEX idx_ogrenci_grup ON ogrenci USING btree (grup_id) WHERE (grup_id IS NOT NULL);
CREATE INDEX idx_ogrenci_isletme_ad ON ogrenci USING btree (isletme_id, ad_soyad);
CREATE INDEX idx_ogrenci_veli_ad_trgm ON ogrenci USING gin (lower((veli_ad_soyad)) gin_trgm_ops) WHERE (veli_ad_soyad IS NOT NULL);

CREATE TABLE oturum_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    isletme_id bigint,
    kullanici_id bigint,
    kullanici_adi character varying(100) NOT NULL,
    olay character varying(20) NOT NULL,
    zaman timestamp(6) without time zone NOT NULL,
    ip character varying(64),
    tarayici character varying(255),
    CONSTRAINT oturum_log_pkey PRIMARY KEY (id),
    CONSTRAINT oturum_log_olay_check CHECK (olay IN ('GIRIS', 'CIKIS', 'BASARISIZ_GIRIS', 'OTURUM_SURESI_DOLDU')),
    CONSTRAINT oturum_log_isletme_id_fkey FOREIGN KEY (isletme_id) REFERENCES isletme(id),
    CONSTRAINT oturum_log_kullanici_id_fkey FOREIGN KEY (kullanici_id) REFERENCES kullanici(id)
);

CREATE INDEX idx_oturum_log_isletme_zaman ON oturum_log USING btree (isletme_id, zaman DESC);
CREATE INDEX idx_oturum_log_kullanici_zaman ON oturum_log USING btree (kullanici_id, zaman DESC);
CREATE INDEX idx_oturum_log_zaman ON oturum_log USING btree (zaman);

CREATE TABLE refresh_token (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    kullanici_id bigint NOT NULL,
    token character varying(512) NOT NULL,
    expiry_date timestamp(6) with time zone NOT NULL,
    revoked boolean NOT NULL,
    CONSTRAINT refresh_token_pkey PRIMARY KEY (id),
    CONSTRAINT refresh_token_token_key UNIQUE (token),
    CONSTRAINT refresh_token_kullanici_id_fkey FOREIGN KEY (kullanici_id) REFERENCES kullanici(id)
);

CREATE INDEX idx_refresh_token_expiry ON refresh_token USING btree (expiry_date);
CREATE INDEX idx_refresh_token_kullanici ON refresh_token USING btree (kullanici_id) WHERE (NOT revoked);

CREATE TABLE abonelik_odeme (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    abonelik_id bigint NOT NULL,
    hesap_id bigint,
    kullanici_id bigint,
    isletme_id bigint NOT NULL,
    tutar numeric(10,2) NOT NULL,
    odeme_sekli character varying(20) NOT NULL,
    odeme_tarihi date NOT NULL,
    kayit_tarih timestamp(6) without time zone NOT NULL,
    CONSTRAINT abonelik_odeme_pkey PRIMARY KEY (id),
    CONSTRAINT abonelik_odeme_hesap_tutarli CHECK (((odeme_sekli) = 'HAVALE_EFT') = (hesap_id IS NOT NULL)),
    CONSTRAINT abonelik_odeme_odeme_sekli_check CHECK (odeme_sekli IN ('NAKIT', 'KART', 'HAVALE_EFT')),
    CONSTRAINT abonelik_odeme_tutar_check CHECK (tutar > 0),
    CONSTRAINT abonelik_odeme_abonelik_id_fkey FOREIGN KEY (abonelik_id) REFERENCES abonelik(id) ON DELETE CASCADE,
    CONSTRAINT abonelik_odeme_hesap_id_fkey FOREIGN KEY (hesap_id) REFERENCES hesap(id),
    CONSTRAINT abonelik_odeme_kullanici_id_fkey FOREIGN KEY (kullanici_id) REFERENCES kullanici(id),
    CONSTRAINT fk_abonelik_odeme_isletme FOREIGN KEY (abonelik_id, isletme_id) REFERENCES abonelik(id, isletme_id) ON DELETE CASCADE
);

CREATE INDEX idx_abonelik_odeme_abonelik ON abonelik_odeme USING btree (abonelik_id);
CREATE INDEX idx_abonelik_odeme_hesap ON abonelik_odeme USING btree (hesap_id) WHERE (hesap_id IS NOT NULL);
CREATE INDEX idx_abonelik_odeme_isletme_tarih ON abonelik_odeme USING btree (isletme_id, odeme_tarihi) INCLUDE (tutar, odeme_sekli, kullanici_id, hesap_id);

CREATE TABLE envanter_satis (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    isletme_id bigint NOT NULL,
    ogrenci_id bigint NOT NULL,
    kullanici_id bigint,
    set_id bigint,
    set_tutari numeric(10,2) NOT NULL,
    odenen_tutar numeric(10,2) NOT NULL,
    kayit_tarihi timestamp(6) without time zone NOT NULL,
    guncelleme_tarihi timestamp(6) without time zone NOT NULL,
    set_ad character varying(100),
    CONSTRAINT envanter_satis_pkey PRIMARY KEY (id),
    CONSTRAINT uk_envanter_satis_id_isletme UNIQUE (id, isletme_id),
    CONSTRAINT envanter_satis_check CHECK (odenen_tutar <= set_tutari),
    CONSTRAINT envanter_satis_odenen_tutar_check CHECK (odenen_tutar >= 0),
    CONSTRAINT envanter_satis_set_tutari_check CHECK (set_tutari > 0),
    CONSTRAINT envanter_satis_isletme_id_fkey FOREIGN KEY (isletme_id) REFERENCES isletme(id),
    CONSTRAINT envanter_satis_kullanici_id_fkey FOREIGN KEY (kullanici_id) REFERENCES kullanici(id),
    CONSTRAINT envanter_satis_ogrenci_id_fkey FOREIGN KEY (ogrenci_id) REFERENCES ogrenci(id),
    CONSTRAINT envanter_satis_set_id_fkey FOREIGN KEY (set_id) REFERENCES envanter_set(id) ON DELETE SET NULL
);

CREATE INDEX idx_envanter_satis_isletme_kayit ON envanter_satis USING btree (isletme_id, kayit_tarihi);
CREATE INDEX idx_envanter_satis_ogrenci ON envanter_satis USING btree (isletme_id, ogrenci_id);
CREATE INDEX idx_envanter_satis_ogrenci_id ON envanter_satis USING btree (ogrenci_id);
CREATE INDEX idx_envanter_satis_set ON envanter_satis USING btree (set_id) WHERE (set_id IS NOT NULL);

CREATE TABLE envanter_set_kalem (
    set_id bigint NOT NULL,
    envanter_id bigint NOT NULL,
    CONSTRAINT envanter_set_kalem_pkey PRIMARY KEY (set_id, envanter_id),
    CONSTRAINT envanter_set_kalem_envanter_id_fkey FOREIGN KEY (envanter_id) REFERENCES envanter(id),
    CONSTRAINT envanter_set_kalem_set_id_fkey FOREIGN KEY (set_id) REFERENCES envanter_set(id) ON DELETE CASCADE
);

CREATE INDEX idx_envanter_set_kalem_envanter ON envanter_set_kalem USING btree (envanter_id);

CREATE TABLE ogrenci_odeme (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ogrenci_id bigint NOT NULL,
    hesap_id bigint,
    kullanici_id bigint,
    isletme_id bigint NOT NULL,
    yil integer NOT NULL,
    ay integer NOT NULL,
    odenen_tutar numeric(10,2) NOT NULL,
    odeme_sekli character varying(20),
    odeme_tarihi date,
    kayit_tarih timestamp(6) without time zone NOT NULL,
    "not" character varying(255),
    CONSTRAINT ogrenci_odeme_pkey PRIMARY KEY (id),
    CONSTRAINT ogrenci_odeme_ay_tekil UNIQUE (ogrenci_id, yil, ay),
    CONSTRAINT ogrenci_odeme_ay_check CHECK ((ay >= 1) AND (ay <= 12)),
    CONSTRAINT ogrenci_odeme_dolu CHECK ((odenen_tutar > 0) OR ("not" IS NOT NULL)),
    CONSTRAINT ogrenci_odeme_hesap_tutarli CHECK (((odeme_sekli) = 'HAVALE_EFT') = (hesap_id IS NOT NULL)),
    CONSTRAINT ogrenci_odeme_odeme_sekli_check CHECK (odeme_sekli IN ('NAKIT', 'KART', 'HAVALE_EFT')),
    CONSTRAINT ogrenci_odeme_odeme_tutarli CHECK ((odenen_tutar = 0) OR ((odeme_sekli IS NOT NULL) AND (odeme_tarihi IS NOT NULL))),
    CONSTRAINT ogrenci_odeme_odenen_tutar_check CHECK (odenen_tutar >= 0),
    CONSTRAINT ogrenci_odeme_yil_check CHECK ((yil >= 2000) AND (yil <= 2100)),
    CONSTRAINT fk_ogrenci_odeme_isletme FOREIGN KEY (ogrenci_id, isletme_id) REFERENCES ogrenci(id, isletme_id) ON DELETE CASCADE,
    CONSTRAINT ogrenci_odeme_hesap_id_fkey FOREIGN KEY (hesap_id) REFERENCES hesap(id),
    CONSTRAINT ogrenci_odeme_kullanici_id_fkey FOREIGN KEY (kullanici_id) REFERENCES kullanici(id),
    CONSTRAINT ogrenci_odeme_ogrenci_id_fkey FOREIGN KEY (ogrenci_id) REFERENCES ogrenci(id) ON DELETE CASCADE
);

CREATE INDEX idx_ogrenci_odeme_hesap ON ogrenci_odeme USING btree (hesap_id) WHERE (hesap_id IS NOT NULL);
CREATE INDEX idx_ogrenci_odeme_isletme_donem ON ogrenci_odeme USING btree (isletme_id, yil, ay) INCLUDE (ogrenci_id, odenen_tutar);
CREATE INDEX idx_ogrenci_odeme_isletme_tarih ON ogrenci_odeme USING btree (isletme_id, odeme_tarihi) INCLUDE (odenen_tutar, odeme_sekli, kullanici_id, hesap_id) WHERE (odeme_tarihi IS NOT NULL);

CREATE TABLE ogrenci_transfer (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    isletme_id bigint NOT NULL,
    ogrenci_id bigint NOT NULL,
    kaynak_grup_id bigint,
    hedef_grup_id bigint,
    talep_eden_id bigint,
    karar_veren_id bigint,
    kaynak_grup_ad character varying(255),
    hedef_grup_ad character varying(255) NOT NULL,
    durum character varying(20) NOT NULL,
    aciklama character varying(500),
    talep_tarihi timestamp(6) without time zone NOT NULL,
    karar_tarihi timestamp(6) without time zone,
    karar_notu character varying(500),
    CONSTRAINT ogrenci_transfer_pkey PRIMARY KEY (id),
    CONSTRAINT ogrenci_transfer_durum_check CHECK (durum IN ('BEKLIYOR', 'ONAYLANDI', 'REDDEDILDI', 'IPTAL')),
    CONSTRAINT ogrenci_transfer_hedef_grup_id_fkey FOREIGN KEY (hedef_grup_id) REFERENCES grup(id) ON DELETE SET NULL,
    CONSTRAINT ogrenci_transfer_isletme_id_fkey FOREIGN KEY (isletme_id) REFERENCES isletme(id),
    CONSTRAINT ogrenci_transfer_karar_veren_id_fkey FOREIGN KEY (karar_veren_id) REFERENCES kullanici(id),
    CONSTRAINT ogrenci_transfer_kaynak_grup_id_fkey FOREIGN KEY (kaynak_grup_id) REFERENCES grup(id) ON DELETE SET NULL,
    CONSTRAINT ogrenci_transfer_ogrenci_id_fkey FOREIGN KEY (ogrenci_id) REFERENCES ogrenci(id) ON DELETE CASCADE,
    CONSTRAINT ogrenci_transfer_talep_eden_id_fkey FOREIGN KEY (talep_eden_id) REFERENCES kullanici(id)
);

CREATE INDEX idx_ogrenci_transfer_isletme_durum ON ogrenci_transfer USING btree (isletme_id, durum);
CREATE INDEX idx_ogrenci_transfer_ogrenci ON ogrenci_transfer USING btree (ogrenci_id, talep_tarihi DESC);
CREATE UNIQUE INDEX uk_ogrenci_transfer_bekleyen ON ogrenci_transfer USING btree (ogrenci_id) WHERE ((durum) = 'BEKLIYOR');

CREATE TABLE rezervasyon (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    saha_id bigint NOT NULL,
    isletme_id bigint NOT NULL,
    kullanici_id bigint,
    abonelik_id bigint,
    iptal_eden_id bigint,
    ad_soyad character varying(255) NOT NULL,
    baslangic_tarih timestamp(6) without time zone NOT NULL,
    bitis_tarih timestamp(6) without time zone NOT NULL,
    durum character varying(20) NOT NULL,
    tel_no character varying(11) NOT NULL,
    odeme_yontemi character varying(20),
    odeme_durumu character varying(20) NOT NULL,
    odenecek_tutar numeric(10,2) NOT NULL,
    kayit_tarih timestamp(6) without time zone,
    iptal_tarih timestamp(6) without time zone,
    iptal_neden character varying(255),
    CONSTRAINT rezervasyon_pkey PRIMARY KEY (id),
    CONSTRAINT uk_rezervasyon_id_isletme UNIQUE (id, isletme_id),
