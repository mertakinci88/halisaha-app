-- Öğrencinin gruplar arası transferi: personel talep açar, admin onaylar ya da reddeder.
-- Onaylanınca öğrencinin grubu hedef gruba geçer. Kayıtlar öğrencinin geçmişi olarak saklanır;
-- grup adları talep anında kopyalanır, böylece grup sonradan silinse / adı değişse de geçmiş okunur kalır.
CREATE TABLE ogrenci_transfer (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isletme_id       BIGINT       NOT NULL REFERENCES isletme (id),
    ogrenci_id       BIGINT       NOT NULL REFERENCES ogrenci (id) ON DELETE CASCADE,
    kaynak_grup_id   BIGINT       REFERENCES grup (id) ON DELETE SET NULL,
    kaynak_grup_ad   VARCHAR(255),
    hedef_grup_id    BIGINT       REFERENCES grup (id) ON DELETE SET NULL,
    hedef_grup_ad    VARCHAR(255) NOT NULL,
    durum            VARCHAR(20)  NOT NULL CHECK (durum IN ('BEKLIYOR', 'ONAYLANDI', 'REDDEDILDI', 'IPTAL')),
    aciklama         VARCHAR(500),
    talep_eden_id    BIGINT       REFERENCES kullanici (id),
    talep_tarihi     TIMESTAMP(6) NOT NULL,
    karar_veren_id   BIGINT       REFERENCES kullanici (id),
    karar_tarihi     TIMESTAMP(6),
    karar_notu       VARCHAR(500)
);

CREATE INDEX idx_ogrenci_transfer_ogrenci ON ogrenci_transfer (ogrenci_id, talep_tarihi DESC);
CREATE INDEX idx_ogrenci_transfer_isletme_durum ON ogrenci_transfer (isletme_id, durum);
-- Bir öğrencinin aynı anda en fazla bir bekleyen talebi olabilir
CREATE UNIQUE INDEX uk_ogrenci_transfer_bekleyen ON ogrenci_transfer (ogrenci_id) WHERE durum = 'BEKLIYOR';
