-- Envanter satışının ödemeleri tek tek tutulur: her ödemenin kendi tarihi, tutarı ve yöntemi vardır.
-- Böylece sonradan alınan ek ödeme, satışın ilk gününe değil kendi gününe yazılır (raporlar ödeme tarihine göre çalışır).
-- envanter_satis.odenen_tutar bu ödemelerin toplamı olarak kalır.

CREATE TABLE envanter_satis_odeme (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    satis_id     BIGINT         NOT NULL REFERENCES envanter_satis (id) ON DELETE CASCADE,
    tutar        NUMERIC(10, 2) NOT NULL CHECK (tutar > 0),
    -- Yöntem kaydı olmayan eski satışlarda boş kalır
    odeme_sekli  VARCHAR(20)    CHECK (odeme_sekli IN ('NAKIT', 'KART', 'HAVALE_EFT')),
    hesap_id     BIGINT         REFERENCES hesap (id),
    odeme_tarihi TIMESTAMP(6)   NOT NULL,
    kullanici_id BIGINT         REFERENCES kullanici (id),
    CONSTRAINT envanter_satis_odeme_hesap_tutarli CHECK ((odeme_sekli = 'HAVALE_EFT') = (hesap_id IS NOT NULL))
);

CREATE INDEX idx_envanter_satis_odeme_satis ON envanter_satis_odeme (satis_id);
CREATE INDEX idx_envanter_satis_odeme_tarih ON envanter_satis_odeme (odeme_tarihi);

-- Mevcut satışlar: o ana kadar ödenen tutar, satışın kayıt tarihinde yapılmış tek ödeme sayılır
INSERT INTO envanter_satis_odeme (satis_id, tutar, odeme_sekli, hesap_id, odeme_tarihi, kullanici_id)
SELECT id, odenen_tutar, odeme_sekli, hesap_id, kayit_tarihi, kullanici_id
FROM envanter_satis
WHERE odenen_tutar > 0;

-- Yöntem ve hesap artık ödeme satırında tutulur (V22'de satışa eklenmişti)
ALTER TABLE envanter_satis DROP CONSTRAINT envanter_satis_hesap_tutarli;
ALTER TABLE envanter_satis DROP COLUMN odeme_sekli, DROP COLUMN hesap_id;
