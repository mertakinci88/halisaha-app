-- Abonelik sistemi: müşteri bir sahayı haftanın belli günü ve saatinde 1 yıl boyunca tutar; her hafta için bir rezervasyon oluşur.

-- Aboneler menüsü personele ayrıca verilebilir
ALTER TABLE kullanici_yetki DROP CONSTRAINT IF EXISTS kullanici_yetki_modul_check;
ALTER TABLE kullanici_yetki ADD CONSTRAINT kullanici_yetki_modul_check
    CHECK (modul IN ('OGRENCI', 'GRUP', 'SAHA', 'URUN', 'YOKLAMA', 'ENVANTER', 'HESAP', 'TRANSFER', 'ABONELIK'));

-- İşletmenin standart abonelik ücreti (kayıt formunda varsayılan olarak gelir, elle değiştirilebilir)
CREATE TABLE abonelik_ayar (
    isletme_id    BIGINT         PRIMARY KEY REFERENCES isletme (id),
    standart_ucret NUMERIC(10, 2) NOT NULL CHECK (standart_ucret >= 0)
);

CREATE TABLE abonelik (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isletme_id     BIGINT         NOT NULL REFERENCES isletme (id),
    saha_id        BIGINT         NOT NULL REFERENCES saha (id),
    ad_soyad       VARCHAR(255)   NOT NULL,
    tel_no         VARCHAR(11)    NOT NULL,
    -- Haftanın günü: 1 = Pazartesi ... 7 = Pazar
    hafta_gunu     INTEGER       NOT NULL CHECK (hafta_gunu BETWEEN 1 AND 7),
    -- İşletme günü 12:00'da başlar, 02:00'de biter: 12-25 (24 = 00:00, 25 = 01:00)
    baslangic_saat INTEGER       NOT NULL CHECK (baslangic_saat BETWEEN 12 AND 25),
    sure_saat      INTEGER       NOT NULL CHECK (sure_saat >= 1),
    baslangic_tarih DATE          NOT NULL,
    -- Başlangıç tarihinden 1 yıl sonrası; kayıtta otomatik hesaplanır
    bitis_tarih    DATE           NOT NULL,
    durum          VARCHAR(20)    NOT NULL CHECK (durum IN ('AKTIF', 'IPTAL')),
    -- Abonelik için anlaşılan toplam tutar
    ucret          NUMERIC(10, 2) NOT NULL CHECK (ucret > 0),
    iptal_tarih    TIMESTAMP(6),
    "not"          VARCHAR(255),
    kullanici_id   BIGINT         REFERENCES kullanici (id),
    kayit_tarih    TIMESTAMP(6)   NOT NULL,
    CONSTRAINT abonelik_saat_sinir CHECK (baslangic_saat + sure_saat <= 26),
    CONSTRAINT abonelik_tarih_sira CHECK (bitis_tarih > baslangic_tarih)
);

CREATE INDEX idx_abonelik_isletme ON abonelik (isletme_id, durum);

-- Aboneliğe alınan ödemeler (kayıtta ilk ödeme, sonra kalan ödemeler)
CREATE TABLE abonelik_odeme (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    abonelik_id  BIGINT         NOT NULL REFERENCES abonelik (id) ON DELETE CASCADE,
    tutar        NUMERIC(10, 2) NOT NULL CHECK (tutar > 0),
    odeme_sekli  VARCHAR(20)    NOT NULL CHECK (odeme_sekli IN ('NAKIT', 'KART', 'HAVALE_EFT')),
    hesap_id     BIGINT         REFERENCES hesap (id),
    odeme_tarihi DATE           NOT NULL,
    kullanici_id BIGINT         REFERENCES kullanici (id),
    kayit_tarih  TIMESTAMP(6)   NOT NULL,
    CONSTRAINT abonelik_odeme_hesap_tutarli CHECK ((odeme_sekli = 'HAVALE_EFT') = (hesap_id IS NOT NULL))
);

CREATE INDEX idx_abonelik_odeme_abonelik ON abonelik_odeme (abonelik_id);
CREATE INDEX idx_abonelik_odeme_tarih ON abonelik_odeme (odeme_tarihi);

-- Aboneliğin oluşturduğu haftalık rezervasyonlar abonelige bağlanır (takvimde "Abone" olarak görünür)
ALTER TABLE rezervasyon ADD COLUMN abonelik_id BIGINT REFERENCES abonelik (id);
CREATE INDEX idx_rezervasyon_abonelik ON rezervasyon (abonelik_id);
