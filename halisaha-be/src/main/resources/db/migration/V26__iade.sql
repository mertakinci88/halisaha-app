-- İade: alınan bir ödemenin (kısmen ya da tamamen) geri verilmesi. Rezervasyon, öğrenci aylık ödemesi, envanter satışı ve abonelik için ortak tablo;
-- her kayıt tam olarak bir kaynağa bağlıdır. Ödeme kayıtları değişmez; iade ayrı kayıt olarak raporlarda iade tarihinde düşülür.
CREATE TABLE iade (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isletme_id       BIGINT         NOT NULL REFERENCES isletme (id),
    rezervasyon_id   BIGINT         REFERENCES rezervasyon (id) ON DELETE CASCADE,
    ogrenci_odeme_id BIGINT         REFERENCES ogrenci_odeme (id) ON DELETE CASCADE,
    envanter_satis_id BIGINT        REFERENCES envanter_satis (id) ON DELETE CASCADE,
    abonelik_id      BIGINT         REFERENCES abonelik (id) ON DELETE CASCADE,
    tutar            NUMERIC(10, 2) NOT NULL CHECK (tutar > 0),
    iade_sekli       VARCHAR(20)    NOT NULL CHECK (iade_sekli IN ('NAKIT', 'KART', 'HAVALE_EFT')),
    hesap_id         BIGINT         REFERENCES hesap (id),
    iade_tarihi      DATE           NOT NULL,
    neden            VARCHAR(255),
    kullanici_id     BIGINT         REFERENCES kullanici (id),
    kayit_tarih      TIMESTAMP(6)   NOT NULL,
    CONSTRAINT iade_tek_kaynak CHECK (
        (rezervasyon_id IS NOT NULL)::int + (ogrenci_odeme_id IS NOT NULL)::int
            + (envanter_satis_id IS NOT NULL)::int + (abonelik_id IS NOT NULL)::int = 1),
    CONSTRAINT iade_hesap_tutarli CHECK ((iade_sekli = 'HAVALE_EFT') = (hesap_id IS NOT NULL))
);

CREATE INDEX idx_iade_isletme_tarih ON iade (isletme_id, iade_tarihi);
CREATE INDEX idx_iade_rezervasyon ON iade (rezervasyon_id) WHERE rezervasyon_id IS NOT NULL;
CREATE INDEX idx_iade_ogrenci_odeme ON iade (ogrenci_odeme_id) WHERE ogrenci_odeme_id IS NOT NULL;
CREATE INDEX idx_iade_envanter_satis ON iade (envanter_satis_id) WHERE envanter_satis_id IS NOT NULL;
CREATE INDEX idx_iade_abonelik ON iade (abonelik_id) WHERE abonelik_id IS NOT NULL;
