-- Kullanıcı bazlı izleme: kim iptal etti, kim ne zaman giriş/çıkış yaptı; kullanıcı raporları için gerekli indeksler.

-- Rezervasyon iptali: ne zaman, kim, neden (bu alanlar eklenmeden önce iptal edilenlerde boş kalır)
ALTER TABLE rezervasyon
    ADD COLUMN iptal_tarih    TIMESTAMP(6),
    ADD COLUMN iptal_eden_id  BIGINT REFERENCES kullanici (id),
    ADD COLUMN iptal_neden    VARCHAR(255);

-- Abonelik iptali: kim ve neden (iptal_tarih zaten vardı)
ALTER TABLE abonelik
    ADD COLUMN iptal_eden_id  BIGINT REFERENCES kullanici (id),
    ADD COLUMN iptal_neden    VARCHAR(255);

-- Giriş / çıkış geçmişi. Başarısız girişler de tutulur; kullanıcı adı yanlışsa kullanici_id ve isletme_id boştur.
CREATE TABLE oturum_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isletme_id    BIGINT       REFERENCES isletme (id),
    kullanici_id  BIGINT       REFERENCES kullanici (id),
    kullanici_adi VARCHAR(100) NOT NULL,
    olay          VARCHAR(20)  NOT NULL CHECK (olay IN ('GIRIS', 'CIKIS', 'BASARISIZ_GIRIS')),
    zaman         TIMESTAMP(6) NOT NULL,
    ip            VARCHAR(64),
    tarayici      VARCHAR(255)
);
CREATE INDEX idx_oturum_log_isletme_zaman ON oturum_log (isletme_id, zaman DESC);
CREATE INDEX idx_oturum_log_kullanici_zaman ON oturum_log (kullanici_id, zaman DESC);

-- Kasa raporu (kullanıcı bazlı tahsilat) ödeme tablolarını kullanıcıya göre toplar: kullanıcı kolonu da kapsayan indeksle tablo okunmaz
DROP INDEX idx_rezervasyon_odeme_isletme_tarih;
CREATE INDEX idx_rezervasyon_odeme_isletme_tarih ON rezervasyon_odeme (isletme_id, odeme_tarihi) INCLUDE (tutar, yontem, kullanici_id);
DROP INDEX idx_ogrenci_odeme_isletme_tarih;
CREATE INDEX idx_ogrenci_odeme_isletme_tarih ON ogrenci_odeme (isletme_id, odeme_tarihi) INCLUDE (odenen_tutar, odeme_sekli, kullanici_id) WHERE odeme_tarihi IS NOT NULL;
DROP INDEX idx_envanter_satis_odeme_isletme_tarih;
CREATE INDEX idx_envanter_satis_odeme_isletme_tarih ON envanter_satis_odeme (isletme_id, odeme_tarihi) INCLUDE (tutar, odeme_sekli, kullanici_id);
DROP INDEX idx_abonelik_odeme_isletme_tarih;
CREATE INDEX idx_abonelik_odeme_isletme_tarih ON abonelik_odeme (isletme_id, odeme_tarihi) INCLUDE (tutar, odeme_sekli, kullanici_id);

-- İşlem sayıları: kullanıcının girdiği rezervasyonlar (abonelik haftaları hariç) ve iptal ettikleri
CREATE INDEX idx_rezervasyon_isletme_kayit ON rezervasyon (isletme_id, kayit_tarih) INCLUDE (kullanici_id) WHERE abonelik_id IS NULL;
CREATE INDEX idx_rezervasyon_isletme_iptal ON rezervasyon (isletme_id, iptal_tarih) WHERE durum = 'IPTAL';
