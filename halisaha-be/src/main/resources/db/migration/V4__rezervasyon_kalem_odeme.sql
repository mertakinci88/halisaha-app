-- Rezervasyon tutarı kalem kalem (saha ücreti + kafeterya ürünleri), tahsilatlar ayrı tabloda tutulur.
-- Kalemde birim fiyat o anki fiyatın kopyasıdır; saha/ürün fiyatı sonradan değişse de geçmiş değişmez.

CREATE TABLE rezervasyon_kalem (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rezervasyon_id   BIGINT         NOT NULL REFERENCES rezervasyon (id) ON DELETE CASCADE,
    tip              VARCHAR(10)    NOT NULL CHECK (tip IN ('SAHA', 'URUN')),
    urun_id          BIGINT         REFERENCES urun (id),
    aciklama         VARCHAR(255)   NOT NULL,
    miktar           NUMERIC(8, 2)  NOT NULL CHECK (miktar > 0),
    birim_fiyat      NUMERIC(10, 2) NOT NULL CHECK (birim_fiyat >= 0),
    tutar            NUMERIC(10, 2) NOT NULL CHECK (tutar >= 0),
    olusturma_tarihi TIMESTAMP(6)   NOT NULL,
    CHECK (tip <> 'URUN' OR urun_id IS NOT NULL)
);

CREATE INDEX idx_rezervasyon_kalem_rezervasyon ON rezervasyon_kalem (rezervasyon_id);

CREATE TABLE odeme (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rezervasyon_id BIGINT         NOT NULL REFERENCES rezervasyon (id),
    tip            VARCHAR(10)    NOT NULL CHECK (tip IN ('KAPORA', 'KISMI', 'ODEME')),
    tutar          NUMERIC(10, 2) NOT NULL CHECK (tutar > 0),
    yontem         VARCHAR(20)    NOT NULL CHECK (yontem IN ('NAKIT', 'KART', 'HAVALE_EFT')),
    odeme_tarihi   TIMESTAMP(6)   NOT NULL,
    kullanici_id   BIGINT         REFERENCES kullanici (id)
);

CREATE INDEX idx_odeme_rezervasyon ON odeme (rezervasyon_id);
CREATE INDEX idx_odeme_tarih ON odeme (odeme_tarihi);

-- Ciro raporu sorguları için
CREATE INDEX idx_rezervasyon_baslangic ON rezervasyon (baslangic_tarih);
CREATE INDEX idx_rezervasyon_saha_baslangic ON rezervasyon (saha_id, baslangic_tarih);

-- Ürünler artık rezervasyon_kalem içinde (tip = 'URUN')
DROP TABLE rezervasyon_urun;
