-- Kafeterya ürünleri rezervasyona eklenince stoktan düşer, çıkarılınca/iptalde geri döner.
-- Stok negatife düşemez; her değişiklik stok_hareket tablosunda izlenir.

ALTER TABLE urun ADD CONSTRAINT urun_adet_check CHECK (adet >= 0);

-- Bu özellikten önce eklenmiş ürün kalemlerinde stok düşülmediği için iade de yapılmaz.
ALTER TABLE rezervasyon_kalem ADD COLUMN stok_dusuldu BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE stok_hareket (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    urun_id        BIGINT       NOT NULL REFERENCES urun (id) ON DELETE CASCADE,
    -- Rezervasyon silinse de hareket geçmişi kalır (aciklama rezervasyonu tarif eder)
    rezervasyon_id BIGINT       REFERENCES rezervasyon (id) ON DELETE SET NULL,
    tip            VARCHAR(10)  NOT NULL CHECK (tip IN ('SATIS', 'IADE', 'DUZELTME')),
    degisim        INTEGER      NOT NULL CHECK (degisim <> 0),
    kalan_adet     INTEGER      NOT NULL CHECK (kalan_adet >= 0),
    aciklama       VARCHAR(255),
    kullanici_id   BIGINT       REFERENCES kullanici (id),
    olusma_tarihi  TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_stok_hareket_urun ON stok_hareket (urun_id, olusma_tarihi);
CREATE INDEX idx_stok_hareket_rezervasyon ON stok_hareket (rezervasyon_id);
