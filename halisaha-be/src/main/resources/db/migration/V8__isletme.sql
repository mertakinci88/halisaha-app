-- Çoklu işletme (multi-tenant): tek veritabanı, her işletmeye ait kayıt isletme_id taşır.
-- stok_hareket, rezervasyon_kalem ve odeme işletmesini bağlı oldukları ürün/rezervasyondan alır.
-- SUPER_ADMIN işletmeye bağlı değildir (isletme_id NULL); işletmeleri o yönetir.

CREATE TABLE isletme (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad          VARCHAR(255) NOT NULL,
    yonetici_ad_soyad VARCHAR(255),
    yonetici_tel_no   VARCHAR(255),
    durum       VARCHAR(20)  NOT NULL CHECK (durum IN ('AKTIF', 'PASIF')),
    kayit_tarih TIMESTAMP(6) NOT NULL
);

