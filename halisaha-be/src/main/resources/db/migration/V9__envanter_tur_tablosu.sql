-- Envanter türleri ve türe özel bedenler artık işletme tarafından yönetilir (önceden sabit enum / CHECK kısıtıydı).
CREATE TABLE envanter_tur (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    isletme_id bigint NOT NULL,
    ad character varying(60) NOT NULL,
    bedenli boolean NOT NULL,
    birim character varying(10) DEFAULT 'adet' NOT NULL,
    CONSTRAINT envanter_tur_pkey PRIMARY KEY (id),
    CONSTRAINT uk_envanter_tur_isletme_ad UNIQUE (isletme_id, ad),
    CONSTRAINT envanter_tur_birim_check CHECK (birim IN ('adet', 'çift')),
    CONSTRAINT envanter_tur_isletme_id_fkey FOREIGN KEY (isletme_id) REFERENCES isletme(id)
);

CREATE TABLE envanter_tur_beden (
    tur_id bigint NOT NULL,
    sira integer NOT NULL,
    beden character varying(10) NOT NULL,
    CONSTRAINT envanter_tur_beden_pkey PRIMARY KEY (tur_id, sira),
    CONSTRAINT envanter_tur_beden_tur_id_fkey FOREIGN KEY (tur_id) REFERENCES envanter_tur(id) ON DELETE CASCADE
);

